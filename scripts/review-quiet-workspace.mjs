async function bounds(language,width){
  await page.setViewportSize({width,height:844});
  const metrics=await page.evaluate(()=>{
    const nodes=[...document.querySelectorAll('input:not([type="checkbox"]),select,button.button,.site-header nav a')].filter(el=>el.getBoundingClientRect().width>0);
    const outside=nodes.filter(el=>{const box=el.getBoundingClientRect();return box.x < -1 || box.right > innerWidth+1;}).map(el=>el.id||el.textContent);
    const time=document.querySelector('[data-field="time"]')?.getBoundingClientRect(),frequency=document.querySelector('[data-field="frequency"]')?.getBoundingClientRect();
    return {pageWidth:document.documentElement.scrollWidth, outside, overlap:time&&frequency?time.left<frequency.right&&time.right>frequency.left&&time.top<frequency.bottom&&time.bottom>frequency.top:false};
  });
  expect(metrics.outside).toEqual([]); expect(metrics.pageWidth).toBeLessThanOrEqual(width); expect(metrics.overlap).toBeFalsy();
  matrix.push({language,width,...metrics});
}
